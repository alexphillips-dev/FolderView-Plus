import assert from 'node:assert/strict';
import fs from 'node:fs';
import { installHost, switchHost } from '../helpers/host-theme.mjs';
import { verifySettingsSearchAlignment, verifyBasicToolbarLayout } from './settings-search-layout.mjs';
import { installSettingsIconFont, verifySettingsIconAlignment } from '../helpers/settings-icons.mjs';

const controlsCss=fs.readFileSync(new URL('../fixtures/vendor/aurora-controls.css',import.meta.url),'utf8');
export const registerAuroraControlCases = ({test,baseUrl}) => {
test('Host theme Aurora header icons cannot resize Settings actions', async ({page}) => {
    await page.setViewportSize({width:1180,height:720});
    await page.goto(`${baseUrl}/settings`,{waitUntil:'load'});
    await installSettingsIconFont(page);
    await page.addStyleTag({content:controlsCss+'\nhtml{font-size:10px;--tp-font-heading:Arial,sans-serif}body{font-size:13px}'});
    await page.evaluate(()=>{
        document.documentElement.classList.add('Theme--black');
        const profile=document.createElement('div');profile.id='UserProfile';
        // Markup generated by Aurora enhance.js themeSwitch(), with no server action attached.
        profile.innerHTML='<button type="button" class="tp-theme-switch tp-dark" aria-label="Switch to the light theme"><i class="fa fa-moon-o"></i></button>';
        document.body.prepend(profile);
    });
    await installHost(page,baseUrl,'#fv-settings-root');
    await switchHost(page,await page.evaluate(()=>matchMedia('(prefers-color-scheme: light)').matches));
    const ignored=await page.evaluate(()=>({
        metrics:window.FolderViewPlusFoundationModules.themeIntegration.readNativeControls(document,window),
        icon:{font:getComputedStyle(document.querySelector('.tp-theme-switch')).fontSize,padding:getComputedStyle(document.querySelector('.tp-theme-switch')).padding}
    }));
    assert.deepEqual(ignored,{metrics:null,icon:{font:'16px',padding:'0px'}});
    await verifySettingsSearchAlignment(page);await verifyBasicToolbarLayout(page);
    await verifySettingsIconAlignment(page);
    const measure=()=>page.evaluate(()=>{
        const reference=getComputedStyle(document.querySelector('.fv-defaults-editor-link'));
        return [...document.querySelectorAll('.fv-mode-toggle button,#fv-run-wizard,[data-toolbar-type] .folder-toolbar button')].map(node=>{
            const style=getComputedStyle(node),rect=node.getBoundingClientRect();
            return {label:node.textContent.trim(),font:style.fontSize,weight:style.fontWeight,padding:style.padding,
                expectedFont:reference.fontSize,expectedWeight:reference.fontWeight,height:rect.height};
        });
    });
    const verify=async()=>{
        for(const control of await measure()){
            assert.equal(control.font,control.expectedFont,control.label);
            assert.equal(control.weight,control.expectedWeight,control.label);
            assert.equal(control.padding,'0px 8.5px',control.label);
            assert.ok(control.height>=30,control.label);
        }
    };
    await verify();
    await page.evaluate(()=>{
        const action=document.createElement('button');action.type='button';action.id='fixture-native-text-action';action.textContent='Native action';
        document.body.append(action);window.fixtureHostBinding.runApply('native-action-added');
    });
    assert.equal(await page.evaluate(()=>window.FolderViewPlusFoundationModules.themeIntegration.readNativeControls(document,window).fontSize),'12px');
    await verify();
    await page.setViewportSize({width:1180,height:720});
    await verifySettingsIconAlignment(page);
    const before=await page.evaluate(()=>window.fixtureHostApplyCount);
    await page.evaluate(()=>{
        const profile=document.getElementById('UserProfile');profile.replaceWith(profile.cloneNode(true));
        window.dispatchEvent(new CustomEvent('folderviewplus:theme-change'));
    });
    await page.waitForFunction(before=>window.fixtureHostApplyCount>before,before);
    await verify();
    await page.locator('#docker-sort-mode').first().focus();
    assert.equal(await page.locator('#docker-sort-mode').first().evaluate(node=>node===document.activeElement),true);
    await page.evaluate(()=>{
        document.getElementById('fixture-native-text-action').remove();window.fixtureHostMode='safe';
        window.fixtureHostBinding.runApply('recovery');
    });
    assert.equal(await page.evaluate(()=>document.documentElement.dataset.fvHostControls),'fallback');
    await verify();
    await page.evaluate(()=>{window.fixtureHostMode='auto';window.fixtureHostBinding.runApply('restore');});
    await page.waitForFunction(()=>document.getAnimations().every(animation=>animation.playState!=='running'));
    await page.evaluate(()=>window.fixtureHostBinding.disconnect());
});
};
